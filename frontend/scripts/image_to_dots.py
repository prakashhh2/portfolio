"""Turn an image into the dot-matrix background for PeteOS.

Usage:  python3 scripts/image_to_dots.py IMAGE [--cols 160] [--invert]
Writes: src/portfolio/background.ts

Each cell becomes a brightness level 0-3 (0 = no dot). Bright parts of the image
become big, bright dots. Use --invert for dark subjects on a light background.
Only use images you have the rights to.
"""
import argparse
import json
from pathlib import Path

from PIL import Image, ImageOps

CELL_ASPECT = 1.0  # dots sit on a square grid
OUT = Path(__file__).resolve().parent.parent / "src" / "portfolio" / "background.ts"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("--cols", type=int, default=160)
    ap.add_argument("--invert", action="store_true")
    args = ap.parse_args()

    img = ImageOps.exif_transpose(Image.open(args.image)).convert("L")
    if args.invert:
        img = ImageOps.invert(img)
    rows = max(1, round(args.cols * img.height / img.width * CELL_ASPECT))
    small = ImageOps.autocontrast(img.resize((args.cols, rows), Image.LANCZOS), cutoff=1)
    pixels = small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata()
    levels = "".join(str(min(3, v * 4 // 256)) for v in pixels)

    OUT.write_text(
        "// Generated by scripts/image_to_dots.py. Do not edit by hand.\n"
        "// null = use the built-in animated dotted landscape.\n"
        f"export const BACKGROUND: {{ cols: number; rows: number; levels: string }} | null = "
        f"{json.dumps({'cols': args.cols, 'rows': rows, 'levels': levels})}\n"
    )
    for r in range(rows):
        print("".join(" .:o"[int(c)] for c in levels[r * args.cols:(r + 1) * args.cols]).rstrip())
    print(f"\nwrote {OUT} ({args.cols}x{rows})")


if __name__ == "__main__":
    main()
