"""Turn a portrait photo into ASCII art for PeteOS (neofetch + welcome screen).

Usage:  python3 scripts/portrait_to_ascii.py PHOTO [--width 40]
Writes: src/portfolio/portrait.ts

Bright background (a plain wall) becomes blank space; the subject is mapped so
brighter pixels use denser characters, which reads as a positive image on the
dark CRT screen.
"""
import argparse
import json
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

RAMP = " .:-=+*#%@"
CHAR_ASPECT = 0.5  # terminal cells are about twice as tall as wide
OUT = Path(__file__).resolve().parent.parent / "src" / "portfolio" / "portrait.ts"


def is_background(rgb, threshold):
    r, g, b = rgb
    return min(r, g, b) >= threshold and max(r, g, b) - min(r, g, b) < 25


def convert(path, width, bg_threshold):
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")

    # Crop to the subject: everything that is not plain light background.
    small = img.resize((img.width // 8, img.height // 8))
    mask = Image.new("L", small.size)
    pixels = small.get_flattened_data() if hasattr(small, "get_flattened_data") else small.getdata()
    mask.putdata([0 if is_background(p, bg_threshold) else 255 for p in pixels])
    mask = mask.filter(ImageFilter.MinFilter(3))  # drop specks of noise
    box = mask.getbbox()
    if box:
        img = img.crop(tuple(v * 8 for v in box))

    height = max(1, round(width * img.height / img.width * CHAR_ASPECT))
    cells = img.resize((width, height), Image.LANCZOS)
    gray = ImageOps.autocontrast(cells.convert("L"), cutoff=2)

    lines = []
    for y in range(height):
        row = ""
        for x in range(width):
            if is_background(cells.getpixel((x, y)), bg_threshold):
                row += " "
            else:
                v = gray.getpixel((x, y)) / 255
                row += RAMP[min(len(RAMP) - 1, 1 + int(v * (len(RAMP) - 1)))]
        lines.append(row.rstrip())
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("photo")
    ap.add_argument("--width", type=int, default=40)
    ap.add_argument("--bg-threshold", type=int, default=215, help="0-255; raise if the background is not removed")
    args = ap.parse_args()
    lines = convert(args.photo, args.width, args.bg_threshold)
    OUT.write_text(
        "// Generated by scripts/portrait_to_ascii.py. Do not edit by hand.\n"
        f"export const PORTRAIT: string[] | null = {json.dumps(lines, indent=2)}\n"
    )
    print("\n".join(lines))
    print(f"\nwrote {OUT} ({args.width}x{len(lines)})")


if __name__ == "__main__":
    main()
